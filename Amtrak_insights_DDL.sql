--OnTrack SQL Create Tables:
CREATE TABLE [OnTrack.Station] (
	stationCode CHAR(3) NOT NULL,
	stationName VARCHAR(60),
	stationState VARCHAR(50),
	stationCity VARCHAR(50),
	stationURL VARCHAR(200),
	CONSTRAINT pk_Station_stationCode PRIMARY KEY (stationCode));

CREATE TABLE [OnTrack.Budget] (
	budgetId CHAR(5) NOT NULL,
	budgetType VARCHAR(15),
	budgetPlanYear CHAR(4),
	budgetTotal DECIMAL(12,2),
	budgetYear CHAR(4),
	budgetAllocation DECIMAL(12,2),
	stationCode CHAR(3),
	CONSTRAINT pk_Budget_budgetId PRIMARY KEY (budgetId),
	CONSTRAINT fk_Budget_stationCode FOREIGN KEY (stationCode)
		REFERENCES [OnTrack.Station](stationCode)
		ON DELETE CASCADE ON UPDATE CASCADE );

CREATE TABLE [OnTrack.Route] (
	routeId CHAR(3) NOT NULL,
	routeName VARCHAR(40),
	routeType VARCHAR(20),
	routeFrequency INT,
	routeHostRailroad VARCHAR(100),
	CONSTRAINT pk_Route_routeId PRIMARY KEY (routeId));

CREATE TABLE [OnTrack.Route_OTP](
	routeId CHAR(3) NOT NULL,
	routeYear CHAR(4) NOT NULL,
	routeOTP DECIMAL(4,3)
	CONSTRAINT pk_Route_OTP_routeId_routeYear PRIMARY KEY (routeId, routeYear),
	CONSTRAINT fk_Route_OTP_routeId FOREIGN KEY (routeId)
		REFERENCES [OnTrack.Route](routeId)
		ON DELETE CASCADE ON UPDATE CASCADE );

CREATE TABLE [OnTrack.Ridership] (
	ridershipId CHAR(5) NOT NULL,
	ridershipYear CHAR(4),
	ridershipQuantity INT,
	stationCode CHAR(3),
	CONSTRAINT pk_Ridership_ridershipId PRIMARY KEY (ridershipId),
	CONSTRAINT fk_Ridership_stationCode FOREIGN KEY (stationCode)
		REFERENCES [OnTrack.Station](stationCode)
		ON DELETE CASCADE ON UPDATE CASCADE );

CREATE TABLE [OnTrack.Serve] (
	stationCode CHAR(3) NOT NULL,
	routeId CHAR(3) NOT NULL,
	CONSTRAINT pk_Serve_stationCode_routeId PRIMARY KEY (stationCode, routeId),
	CONSTRAINT fk_Serve_stationCode FOREIGN KEY (stationCode)
	     REFERENCES [OnTrack.Station](stationCode)
		 ON DELETE NO ACTION ON UPDATE NO ACTION,
	CONSTRAINT fk_Serve_routeId FOREIGN KEY (routeId)
	    REFERENCES [OnTrack.Route] (routeId)
		ON DELETE NO ACTION ON UPDATE NO ACTION );

